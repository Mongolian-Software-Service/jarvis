-- Сургалтын нэрэнд «захиалж сурах нь» биш, «хийж сурах нь» (2026-10-02).
--
-- Landing page аль хэдийн «хийж сурах нь» байсан; үлдсэн гурав түүнтэй нэг
-- хэлбэрт орж, таван нэр нэг дүрмээр уншигдана. Хураангуй, тайлбар дахь
-- «захиалж угсрах» гэх мэт өгүүлбэрт хүрээгүй — энэ patch зөвхөн нэр.
--
-- `where … and title_mn = <хуучин>`: консолоос нэрийг гараар өөрчилсөн бол
-- тэр мөрийг дарж бичихгүй, зүгээр л алгасна.
begin;
update public.courses set title_mn = 'Бүтэн вэб апп хийж сурах нь'
  where slug = 'fullstack' and title_mn = 'Бүтэн вэб апп захиалж сурах нь';
update public.courses set title_mn = 'Утасны апп хийж сурах нь'
  where slug = 'mobile-app' and title_mn = 'Утасны апп захиалж сурах нь';
update public.courses set title_mn = 'Тоглоом хийж сурах нь'
  where slug = 'toglom' and title_mn = 'Тоглоом захиалж сурах нь';
commit;
