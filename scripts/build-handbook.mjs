#!/usr/bin/env node
/**
 * Print `docs/handbook/*.html` to a PDF the site can hand out.
 *
 * Chrome, rather than a PDF library. A library would mean writing the layout
 * twice — once in CSS for the browser and once in that library's own box model
 * — and would have to be taught to embed a Cyrillic font before it could set a
 * single Mongolian word. Chrome already lays out the document we wrote, already
 * embeds the fonts it used, and is on every machine this project is developed
 * on. The cost is that the build is not reproducible on a machine without it,
 * which is why the PDF is committed rather than built on deploy.
 *
 * The fonts come from the phone app's `node_modules` — the same Inter and
 * JetBrains Mono the product ships, so the handbook is set in the school's own
 * type rather than in whatever the printer happens to have. The HTML carries
 * `__FONTS__` placeholders and this script fills them in, so the file stays
 * openable in a browser from any clone.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

/** Every handbook, keyed by the course slug its card sits on. */
const BOOKS = [
  { slug: "tanilcuulga", source: "docs/handbook/tanilcuulga.html", out: "tsstark-academy-tanilcuulga.pdf" },
  { slug: "code-suuri", source: "docs/handbook/code-suuri.html", out: "tsstark-academy-code-suuri.pdf" },
];

const FONTS = join(root, "apps/mobile/node_modules/@expo-google-fonts");

const CHROMES = [
  process.env.CHROME,
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
].filter(Boolean);

const chrome = CHROMES.find((path) => existsSync(path));
if (!chrome) {
  console.error("✗ No Chrome found. Install Google Chrome, or set CHROME=/path/to/binary.");
  process.exit(1);
}

if (!existsSync(join(FONTS, "inter"))) {
  console.error(`✗ Fonts missing at ${FONTS} — run \`pnpm install\` first.`);
  process.exit(1);
}

/*
 * Diagrams are inlined rather than left as `<img src="figma/…svg">`.
 *
 * An SVG loaded through `<img>` is its own document: it cannot see this page's
 * `@font-face`, so every label would fall back to a system serif and the one
 * full-page picture in the book would be set in the wrong type. Inlined, it
 * inherits — which is also why the font name is rewritten to the one this
 * document declares. The files stay generated by `pnpm diagrams`, for Figma.
 */
function inlineDiagrams(markup) {
  return markup.replace(/<img src="figma\/([\w.-]+)"[^>]*>/g, (_, name) =>
    readFileSync(join(root, "docs/handbook/figma", name), "utf8")
      .replace(/\bfont-family="Inter"/g, 'font-family="Inter H"')
      .replace(/ width="\d+" height="\d+"/, ' width="100%" height="auto"'),
  );
}

for (const book of BOOKS) {
  const SOURCE = join(root, book.source);
  const OUT = join(root, "apps/web/public/handbook", book.out);

  const html = inlineDiagrams(readFileSync(SOURCE, "utf8")).replaceAll("__FONTS__", `file://${FONTS}`);

  /* Chrome reads the page from disk, so the substituted copy has to be a real
     file — and one beside the source, or the relative font URLs would resolve
     from somewhere else. */
  const staged = join(root, "docs/handbook", `.staged-${book.slug}.html`);
  writeFileSync(staged, html);
  mkdirSync(dirname(OUT), { recursive: true });

  try {
    execFileSync(
      chrome,
      [
        "--headless",
        "--disable-gpu",
        "--no-sandbox",
        // Fonts and layout have to finish before the paint.
        "--virtual-time-budget=10000",
        "--no-pdf-header-footer",
        `--print-to-pdf=${OUT}`,
        `file://${staged}`,
      ],
      { stdio: ["ignore", "ignore", "pipe"] },
    );
  } catch (error) {
    console.error("✗ Chrome failed to print:\n", String(error.stderr ?? error.message));
    process.exit(1);
  } finally {
    rmSync(staged, { force: true });
  }

  const size = statSync(OUT).size;
  if (size < 40_000) {
    console.error(`✗ ${OUT} is only ${size} bytes — the page probably rendered empty.`);
    process.exit(1);
  }

  /*
   * Write the two numbers the download card prints back into the constant.
   *
   * They could be measured at request time instead, but a server component
   * that stats a file on every render is paying for a number that changes
   * twice a year — and a hand-kept number is a number that is wrong by the
   * second rebuild. Generated, from the file that was just generated.
   */
  const pages = (readFileSync(OUT).toString("latin1").match(/\/Type\s*\/Page[^s]/g) ?? []).length;
  const kb = Math.round(size / 1024);

  const constants = join(root, "packages/core/src/handbooks.ts");
  const before = readFileSync(constants, "utf8");
  /* The key may be quoted — a slug with a hyphen cannot be a bare property
     name — so the pattern allows either spelling. */
  const after = before.replace(
    new RegExp(`("?${book.slug}"?: \\{ file: "[^"]+", pages: )\\d+(, sizeKb: )\\d+( \\})`),
    `$1${pages}$2${kb}$3`,
  );
  if (after !== before) writeFileSync(constants, after);

  console.log(`✓ ${book.out} — ${pages} pages, ${kb} KB`);
}
