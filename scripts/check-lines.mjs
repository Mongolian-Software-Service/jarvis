#!/usr/bin/env node
/**
 * One file, one screenful: nothing in this repository is longer than 160 lines.
 *
 * The number is not the point — the pressure is. A 400-line component is three
 * components that were never named, and the names are the part worth having:
 * they are what a reader greps for, what the next person can change without
 * reading the other two, and what tells you a piece belongs in
 * `packages/core` rather than beside one screen. A cap makes that pressure
 * constant instead of a thing somebody remembers to apply.
 *
 * **Comments and blank lines do not count.** This codebase explains itself at
 * length on purpose (see CLAUDE.md), and a cap that counted prose would pay
 * for every refactor by deleting the reasoning behind it — which is the one
 * thing here that cannot be recovered by reading the code again. So the limit
 * is 160 lines of *code*, and a well-documented file is allowed to be long on
 * disk.
 *
 * Why this and not ESLint's `max-lines`: lint runs in `apps/web` and
 * `apps/mobile` only. `packages/core` has no ESLint config, and `scripts/` and
 * `supabase/` are not linted at all — so half the repository would be exempt
 * by accident rather than by decision. Everything that is exempt here is
 * exempt on purpose, with the reason written next to it.
 *
 *   node scripts/check-lines.mjs           report and fail
 *   node scripts/check-lines.mjs --list    every file, longest first
 */
import { readFileSync, readdirSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, extname } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const LIMIT = 160;

/** Directories that hold no source of ours. */
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  ".expo",
  ".git",
  ".turbo",
  "dist",
  "build",
  "out",
  "coverage",
]);

const EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".sql", ".css"]);

/**
 * The exemptions, each with the reason it is one.
 *
 * A path is exempt because splitting it is impossible or wrong — never because
 * it is inconvenient to do. Adding to this list is a decision; make it in a
 * review, not on the way past.
 */
const EXEMPT = [
  {
    test: (path) => path === "packages/types/src/database.ts",
    why: "generated by `pnpm db:types` — edits are overwritten on the next run",
  },
  {
    test: (path) => path.startsWith("supabase/migrations/"),
    why: "a migration is history: it has been applied, and rewriting it desynchronises `applied_migrations`",
  },
  {
    test: (path) => path === "supabase/seed.sql",
    why: "course content, not code — 61 lessons of prose that no split makes easier to read",
  },
  {
    test: (path) => path === "apps/web/src/app/globals.css",
    why: "the single source of the palette (§4.1); tokens split across files stop being one place to look",
  },
];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (EXTENSIONS.has(extname(entry))) out.push(full);
  }
  return out;
}

/**
 * Lines of code: blank lines and whole-line comments do not count.
 *
 * Deliberately a scanner rather than a parser — it only has to decide whether
 * a line carries code, and a line with anything but comment on it does. It
 * understands `//`, `/* *\/`, SQL's `--`, and the `{/* *\/}` JSX wrapper.
 */
export function codeLines(source, ext) {
  const lineComment = ext === ".sql" ? "--" : "//";
  let count = 0;
  let inBlock = false;

  for (const raw of source.split("\n")) {
    let line = raw.trim();
    if (!line) continue;

    if (inBlock) {
      const end = line.indexOf("*/");
      if (end === -1) continue;
      // Whatever followed the close on the same line still counts.
      line = line
        .slice(end + 2)
        .replace(/^\}/, "")
        .trim();
      inBlock = false;
      if (!line) continue;
    }

    // Strip any number of complete block comments sitting on this line.
    let guard = 0;
    while (guard++ < 50) {
      const open = line.indexOf("/*");
      if (open === -1) break;
      const close = line.indexOf("*/", open + 2);
      if (close === -1) {
        inBlock = true;
        line = line.slice(0, open).replace(/\{$/, "").trim();
        break;
      }
      line = (line.slice(0, open) + line.slice(close + 2)).trim();
    }

    if (!line) continue;
    if (line.startsWith(lineComment)) continue;
    count += 1;
  }

  return count;
}

const files = walk(root)
  .map((full) => {
    const path = relative(root, full);
    return { path, lines: codeLines(readFileSync(full, "utf8"), extname(full)) };
  })
  .sort((a, b) => b.lines - a.lines);

if (process.argv.includes("--list")) {
  for (const { path, lines } of files) console.log(String(lines).padStart(5), path);
  process.exit(0);
}

const over = files.filter(({ path, lines }) => lines > LIMIT && !EXEMPT.some((e) => e.test(path)));

if (over.length) {
  console.error(`\n${over.length} file(s) over ${LIMIT} lines of code:\n`);
  for (const { path, lines } of over) console.error(`  ${String(lines).padStart(4)}  ${path}`);
  console.error(
    `\nSplit them, or add an exemption to scripts/check-lines.mjs with the reason.\n` +
      `Comments and blank lines are already excluded — do not delete prose to fit.\n`,
  );
  process.exit(1);
}

console.log(`check-lines: ${files.length} files, none over ${LIMIT} lines of code.`);
